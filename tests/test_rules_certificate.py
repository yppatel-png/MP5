"""
Unit & Parity Tests for Feature A: Plan Certificate & Rule Registry.
Covers:
1. Deterministic Rule Registry execution across verified and assumed rules
2. Solver plan parity across synthetic profiles
3. Mutation testing (prerequisite violation, parity violation, credit overload, minimum credit breach, hallucinated course)
4. Cryptographic PlanCertificate canonical SHA-256 seal and tamper detection
5. Zero-dependency PDF export generation
6. Certificate REST APIs (/certificate, /certificate/verify, /certificate.pdf)
"""

import unittest
import copy
from backend.db.seed_loader import load_seed_data
from backend.student.model import StudentStore
from backend.rules import (
    rule_registry,
    pdf_builder,
    PlanCertificate,
    RuleStatus,
    RuleCategory,
)
from backend.planner.solver import multi_semester_planner
from backend.student.diagnostic import diagnostic_engine
from backend.api.plans import (
    generate_student_plan,
    get_plan_certificate,
    verify_plan_certificate,
    export_plan_certificate_pdf,
    PlanGenerateRequest,
    CertificateVerifyRequest,
)

class TestRulesCertificate(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        load_seed_data(reset=True)

    def setUp(self):
        self.profile = StudentStore.get_profile("BH-SW-001")
        self.gaps = diagnostic_engine.compute_skill_gaps("BH-SW-001")
        self.valid_plan = multi_semester_planner.plan_curriculum(
            student_id="BH-SW-001",
            programme_code=self.profile.programme,
            current_semester=self.profile.current_semester,
            cgpa=self.profile.cgpa,
            completed_courses=[c.course_code for c in self.profile.completed_courses],
            skill_gaps=self.gaps.get("gaps", []),
            goal_id=self.profile.goal_id
        )

    def test_01_registry_execution_and_certificate_seal(self):
        """Verifies that rule_registry evaluates all rules and produces a valid cryptographic seal."""
        cert = rule_registry.generate_certificate(self.valid_plan, self.profile.model_dump())
        self.assertIsInstance(cert, PlanCertificate)
        self.assertTrue(cert.is_valid)
        self.assertGreater(cert.summary.total_rules, 5)
        self.assertEqual(cert.summary.failed, 0)
        self.assertEqual(len(cert.certificate_hash), 64)
        self.assertTrue(cert.verify_integrity())

    def test_02_solver_plan_parity_across_profiles(self):
        """Verifies that all plans generated by the solver pass the registry rules without statutory failure."""
        personas = ["BH-SW-001", "BH-HS-001", "BH-UP-001"]
        for pid in personas:
            prof = StudentStore.get_profile(pid)
            gaps = diagnostic_engine.compute_skill_gaps(pid)
            plan = multi_semester_planner.plan_curriculum(
                student_id=pid,
                programme_code=prof.programme,
                current_semester=prof.current_semester,
                cgpa=prof.cgpa,
                completed_courses=[c.course_code for c in prof.completed_courses],
                skill_gaps=gaps.get("gaps", []),
                goal_id=prof.goal_id
            )
            cert = rule_registry.generate_certificate(plan, prof.model_dump())
            self.assertTrue(cert.is_valid, f"Persona {pid} failed certificate verification! Failed: {[r.message for r in cert.results if r.status == RuleStatus.FAIL]}")
            self.assertEqual(cert.summary.failed, 0)

    def test_03_mutation_prerequisite_chain_violation(self):
        """Mutation test: scheduling an advanced course without earlier prerequisite fails prerequisite rule with chain."""
        corrupted = copy.deepcopy(self.valid_plan)
        prof_dict = self.profile.model_dump()
        prof_dict["completed_courses"] = [
            c for c in prof_dict["completed_courses"] if c["course_code"] != "CSL202"
        ]
        # Invert: put dependent course CSL252 in Semester 4, and prerequisite CSL202 later in Semester 5
        corrupted["semesters"][0]["courses"] = [{"code": "CSL252", "credits": 4.0}]
        corrupted["semesters"][1]["courses"] = [{"code": "CSL202", "credits": 4.0}]

        results = rule_registry.run_all(corrupted, prof_dict)
        prereq_res = next((r for r in results if r.rule_id == "rule_prereq_strict_enforcement"), None)
        self.assertIsNotNone(prereq_res)
        self.assertEqual(prereq_res.status, RuleStatus.FAIL)
        self.assertIn("CSL252", prereq_res.message)

    def test_04_mutation_semester_parity_mismatch(self):
        """Mutation test: placing an even semester course in an odd semester fails parity rule."""
        corrupted = copy.deepcopy(self.valid_plan)
        # CSL252 is scheduled for semester_4. Force it into Semester 3 (odd).
        odd_sem = next((s for s in corrupted["semesters"] if s["semester_number"] % 2 != 0), corrupted["semesters"][0])
        odd_sem["courses"].append({
            "code": "CSL252",
            "title": "Design and Analysis of Algorithms",
            "credits": 4.0,
            "course_type": "core"
        })

        results = rule_registry.run_all(corrupted, self.profile.model_dump())
        parity_res = next((r for r in results if r.rule_id == "rule_semester_parity" and r.status == RuleStatus.FAIL), None)
        self.assertIsNotNone(parity_res)
        self.assertEqual(parity_res.status, RuleStatus.FAIL)
        self.assertIn("CSL252", parity_res.message)

    def test_05_mutation_semester_credit_cap_breach(self):
        """Mutation test: exceeding semester credit ceiling fails max credit rule."""
        corrupted = copy.deepcopy(self.valid_plan)
        corrupted["semesters"][0]["total_credits"] = 32.0
        corrupted["semesters"][0]["courses"].extend([
            {"code": "CSL304", "credits": 4.0},
            {"code": "CSL622", "credits": 4.0},
            {"code": "CSL711", "credits": 4.0},
        ])

        results = rule_registry.run_all(corrupted, self.profile.model_dump())
        cap_res = next((r for r in results if r.rule_id == "rule_sem_max_credits" and r.status == RuleStatus.FAIL), None)
        self.assertIsNotNone(cap_res)
        self.assertEqual(cap_res.status, RuleStatus.FAIL)
        self.assertIn("exceeds", cap_res.message)

    def test_06_mutation_minimum_semester_credits(self):
        """Mutation test: scheduling fewer than minimum required credits fails min credits rule."""
        corrupted = copy.deepcopy(self.valid_plan)
        corrupted["semesters"][0]["total_credits"] = 1.0
        corrupted["semesters"][0]["courses"] = [{"code": "LAL201", "credits": 1.0}]

        results = rule_registry.run_all(corrupted, self.profile.model_dump())
        min_res = next((r for r in results if r.rule_id == "rule_sem_min_credits" and r.status == RuleStatus.WARN), None)
        self.assertIsNotNone(min_res)
        self.assertEqual(min_res.status, RuleStatus.WARN)
        self.assertIn("below", min_res.message)

    def test_07_mutation_hallucinated_course_code(self):
        """Mutation test: fabricated course code fails catalogue existence rule."""
        corrupted = copy.deepcopy(self.valid_plan)
        corrupted["semesters"][0]["courses"].append({"code": "FAKE999", "credits": 4.0})

        results = rule_registry.run_all(corrupted, self.profile.model_dump())
        exist_res = next((r for r in results if r.rule_id == "rule_course_catalogue_exists" and r.status == RuleStatus.FAIL), None)
        self.assertIsNotNone(exist_res)
        self.assertEqual(exist_res.status, RuleStatus.FAIL)
        self.assertIn("FAKE999", exist_res.message)

    def test_08_tamper_detection_and_verification(self):
        """Verifies that tampering with plan details triggers hash mismatch and tampered=True."""
        cert = rule_registry.generate_certificate(self.valid_plan, self.profile.model_dump())
        original_hash = cert.certificate_hash

        # Re-verify untampered plan: must match
        res_ok = rule_registry.verify_plan(
            self.valid_plan,
            self.profile.model_dump(),
            expected_certificate_hash=original_hash,
            generated_at=cert.generated_at,
            plan_version_id=cert.plan_version_id
        )
        self.assertFalse(res_ok["tampered"])
        self.assertEqual(res_ok["certificate_hash"], original_hash)

        # Tamper plan by modifying a course code
        tampered_plan = copy.deepcopy(self.valid_plan)
        tampered_plan["semesters"][0]["courses"][0]["code"] = "CSL304"
        res_tampered = rule_registry.verify_plan(
            tampered_plan,
            self.profile.model_dump(),
            expected_certificate_hash=original_hash,
            generated_at=cert.generated_at,
            plan_version_id=cert.plan_version_id
        )
        self.assertTrue(res_tampered["tampered"])
        self.assertNotEqual(res_tampered["certificate_hash"], original_hash)
        self.assertGreater(len(res_tampered["diff"]), 0)

    def test_09_pdf_certificate_generation(self):
        """Verifies pure-Python PDF builder exports a well-formed PDF document."""
        cert = rule_registry.generate_certificate(self.valid_plan, self.profile.model_dump())
        pdf_bytes = pdf_builder.build_certificate_pdf(cert, self.profile.model_dump())

        self.assertIsInstance(pdf_bytes, bytes)
        self.assertTrue(pdf_bytes.startswith(b"%PDF-1.4"))
        self.assertTrue(pdf_bytes.rstrip().endswith(b"%%EOF"))
        self.assertGreater(len(pdf_bytes), 1500)

    def test_10_api_endpoints_certificate_and_verify(self):
        """Tests FastAPI endpoints for /certificate, /certificate/verify, and /certificate.pdf."""
        gen_res = generate_student_plan(PlanGenerateRequest(student_id="BH-SW-001"))
        self.assertIn("certificate", gen_res)

        # GET /certificate
        cert_data = get_plan_certificate("BH-SW-001")
        self.assertIn("certificate_hash", cert_data)
        self.assertTrue(cert_data["is_valid"])

        # POST /certificate/verify
        verify_res = verify_plan_certificate("BH-SW-001", CertificateVerifyRequest(expected_hash=cert_data["certificate_hash"]))
        self.assertFalse(verify_res["tampered"])
        self.assertTrue(verify_res["is_valid"])

        # GET /certificate.pdf
        resp = export_plan_certificate_pdf("BH-SW-001")
        self.assertEqual(resp.media_type, "application/pdf")
        self.assertTrue(resp.body.startswith(b"%PDF-1.4"))

if __name__ == "__main__":
    unittest.main()
